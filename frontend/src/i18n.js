export function td(value) {
  if (value == null) return value
  const raw = String(value)
  const messagePack = messages[langState.current]
  if (messagePack && Object.prototype.hasOwnProperty.call(messagePack, raw)) return messagePack[raw]
  const pack = DYNAMIC_TEXT_MESSAGES[langState.current]
  if (!pack) return raw
  if (Object.prototype.hasOwnProperty.call(pack, raw)) return pack[raw]
  let out = raw
  const entries = Object.entries(pack).sort((a, b) => b[0].length - a[0].length)
  for (const [from, to] of entries) {
    if (from && out.includes(from)) out = out.split(from).join(to)
  }
  return out
}

const ALLOWED_LANGS = new Set(['zh', 'en', 'ru'])

/** 将任意存储值规范为 zh | en | ru，避免非法 localStorage 导致 messages 取不到 */
export function normalizeLang(raw) {
  if (raw == null || raw === '') return 'zh'
  const s = String(raw).trim().toLowerCase()
  return ALLOWED_LANGS.has(s) ? s : 'zh'
}

const initialLang =
  typeof localStorage !== 'undefined' ? localStorage.getItem('lang') : null

export const langState = reactive({
  current: normalizeLang(initialLang),
})

if (typeof localStorage !== 'undefined' && langState.current !== initialLang) {
  localStorage.setItem('lang', langState.current)
}

export function setLanguage(lang) {
  const code = normalizeLang(lang)
  langState.current = code
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('lang', code)
  }
}

function pickMessage(pack, key) {
  if (pack && Object.prototype.hasOwnProperty.call(pack, key)) {
    return pack[key]
  }
  return undefined
}

export function t(key) {
  const locale = langState.current
  const primary = messages[locale]
  const hit = pickMessage(primary, key)
  if (hit !== undefined) return hit
  const zhFallback = pickMessage(messages.zh, key)
  if (zhFallback !== undefined) return zhFallback
  const enFallback = pickMessage(messages.en, key)
  if (enFallback !== undefined) return enFallback
  return key
}